// push function array
let fruits = ["Apple", "Banana"];
fruits.push("Mango");

console.log(fruits);


// pop function array
let fruits = ["Apple", "Banana", "Mango"];
fruits.pop();

console.log(fruits);

//shift function array
let fruits = ["Apple", "Banana", "Mango"];
fruits.shift();

console.log(fruits);


//unshift function array
let fruits = ["Banana", "Mango"];
fruits.unshift("Apple");

console.log(fruits);

